const BY_ID = new Map(DOCUMENT_TEMPLATES.map((item) => [item.id, item]));

export function getDocumentTemplateConfig(templateId: string): DocumentTemplateConfig | undefined {
  return BY_ID.get(templateId);
}

export function getActiveDocumentTemplates(
  roleCategory?: DocumentTemplateConfig["roleCategory"],
): DocumentTemplateConfig[] {
  return DOCUMENT_TEMPLATES.filter(
    (item) => item.active && (!roleCategory || item.roleCategory === roleCategory),
  );
}

export function isEngineBackedTemplate(templateId: string): boolean {
  return Boolean(getDocumentTemplateConfig(templateId)?.engineEnabled);
}
