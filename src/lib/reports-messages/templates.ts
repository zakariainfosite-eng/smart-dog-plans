export function getReportTemplate(templateId: string): ReportTemplateDefinition | undefined {
  return REPORT_TEMPLATES.find((template) => template.id === templateId);
}

export function getTemplatesForRole(roleCategory: RoleCategory): ReportTemplateDefinition[] {
  return REPORT_TEMPLATES.filter((template) => template.roleCategory === roleCategory);
}

export function getReferencePrefixForKind(kind: DocumentKind): "RAP" | "MSG" {
  return kind === "message" ? "MSG" : "RAP";
}
